export function getTrussPage(slug = '') {
  if (slug === '') {
    return {
      ...trussClusterPages.pillar,
      path: BASE_PATH,
      fullUrl: `${SITE_URL}${BASE_PATH}`,
    };
  }

  const page = trussClusterPages[slug];
  if (!page) {
    return null;
  }

  return {
    ...page,
    path: `${BASE_PATH}/${slug}`,
    fullUrl: `${SITE_URL}${BASE_PATH}/${slug}`,
  };
}

export function getTrussSupportPages() {
  return trussClusterOrder.map((slug) => getTrussPage(slug)).filter(Boolean);
}

